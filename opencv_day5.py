import cv2
img=cv2.imread('real.jpg')
gray_img=cv2.cvtColor(img,cv2.COLOR_BGR2GRAY)
img_blur=cv2.GaussianBlur(gray_img,(5,5),0)
edges1=cv2.Canny(img_blur,50,150)
edges2=cv2.Canny(img_blur,10,50)
edges3=cv2.Canny(img_blur,150,250)
edges1=cv2.resize(edges1,(800,600))
edges2=cv2.resize(edges2,(800,600))
edges3=cv2.resize(edges3,(800,600))
cv2.imshow('1',edges1)
cv2.imshow('2',edges2)
cv2.imshow('3',edges3)
cv2.waitKey(0)
cv2.destroyAllWindows()